import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';

const SUFFIX = '.cheat.js';
const EXPORT_PATTERN = /export\s+const\s+([A-Za-z_$][\w$]*Cheat)\s*=/g;
export const GENERATED_BANNER = '// @generated by scripts/cheat-manifest.js; DO NOT EDIT.';
export const normalizeManifestPath = (value) => value.replaceAll('\\', '/');

function files(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = resolve(directory, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}

export function discoverCheatManifestEntries({ definitionsDir }) {
  const root = resolve(definitionsDir);
  const seen = new Map();
  return files(root)
    .filter((file) => file.endsWith(SUFFIX))
    .sort((a, b) => a.localeCompare(b))
    .map((absolutePath) => {
      const relativePath = normalizeManifestPath(relative(root, absolutePath));
      const exports = [...readFileSync(absolutePath, 'utf8').matchAll(EXPORT_PATTERN)].map(
        (match) => match[1]
      );
      if (exports.length !== 1)
        throw new Error(
          `Cheat module "${relativePath}" must export exactly one *Cheat descriptor.`
        );
      const exportName = exports[0];
      if (seen.has(exportName))
        throw new Error(
          `Duplicate cheat export "${exportName}" in "${seen.get(
            exportName
          )}" and "${relativePath}".`
        );
      seen.set(exportName, relativePath);
      return Object.freeze({ absolutePath, relativePath, exportName });
    });
}

export function renderCheatManifest(entries, { outputFile }) {
  const outputDir = dirname(resolve(outputFile));
  const imports = entries.map(({ absolutePath, exportName }) => {
    let path = normalizeManifestPath(relative(outputDir, absolutePath));
    if (!path.startsWith('.')) path = `./${path}`;
    return `import { ${exportName} } from ${JSON.stringify(path)};`;
  });
  return [
    GENERATED_BANNER,
    ...imports,
    '',
    'export const generatedCheats = Object.freeze([',
    ...entries.map(({ exportName }) => `  ${exportName},`),
    ']);',
    '',
  ].join('\n');
}

export function generateCheatManifest(options) {
  const entries = discoverCheatManifestEntries(options);
  const content = renderCheatManifest(entries, options);
  mkdirSync(dirname(resolve(options.outputFile)), { recursive: true });
  writeFileSync(options.outputFile, content, 'utf8');
  return Object.freeze({ entries, content });
}

export function checkCheatManifest(options) {
  const entries = discoverCheatManifestEntries(options);
  const expected = renderCheatManifest(entries, options);
  const actual = existsSync(options.outputFile) ? readFileSync(options.outputFile, 'utf8') : null;
  if (actual !== expected)
    throw new Error(
      `Generated cheat manifest is stale: ${normalizeManifestPath(options.outputFile)}`
    );
  return Object.freeze({ entries, content: actual });
}
